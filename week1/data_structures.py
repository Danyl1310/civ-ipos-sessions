
#Lists
my_list = [1, "hello", True, 1.5]

#Dictionaries
my_dictionary = {1:"one", 2:"two", 3:"three"}
for key, value in my_dictionary.items():
    print(f"{key}, {value}.")

#Tuples
my_tuple = (1, "hello", True, 1.5)
print(my_tuple)

#Sets
my_set = set(my_list)


print(my_list)
print(my_dictionary)
print(my_tuple)
print(my_set)